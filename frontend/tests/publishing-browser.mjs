import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const browser=await chromium.launch({executablePath:process.env.MELKA_BROWSER_EXECUTABLE || undefined,headless:true,args:['--no-sandbox']});
try {
  const page=await browser.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const origin=process.env.MELKA_FRONTEND_ORIGIN;
  await page.goto(origin+'/accounts/login/');
  await page.locator('[name=email]').fill('publish-browser@example.com');
  await page.locator('[name=password]').fill('Publish-browser-password-42');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await page.waitForURL('**/dashboard/');
  await page.goto(origin+'/dashboard/create/Blog/');
  const editor=page.locator('[name=content_en]');
  const toolbar=page.locator('.tutorial-editor').filter({has:editor});
  const invalidResponse=page.waitForResponse(r=>r.url().includes('/api/frontend/admin/Blog/')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Publish tutorial',exact:true}).click();
  assert.equal((await invalidResponse).status(),400);
  await expect(page.getByRole('alert').filter({hasText:'Nothing was saved'})).toContainText('Title');
  await expect(page.getByRole('alert').filter({hasText:'Nothing was saved'})).toContainText('Content');
  await page.locator('[name=title_en]').fill('Browser tutorial publishing check');
  await page.locator('[name=blog_category]').selectOption({label:'Technology'});
  await editor.fill('A tutorial body.');
  for (const [button,marker] of [['Heading','##'],['Bold','**'],['Code','```python'],['Link','](https://example.com)'],['List','- Second step'],['Callout','> **Note:**'],['Table','| Setting | Value |']]) {
    await editor.evaluate(el=>{el.focus();el.setSelectionRange(el.value.length,el.value.length);});
    await toolbar.getByRole('button',{name:button,exact:true}).click();
    await expect(editor).toHaveValue(new RegExp(marker.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
  }
  const written=await editor.inputValue();
  await page.evaluate(()=>localStorage.setItem('melka-blog-new-content_en','Restored browser draft'));
  await toolbar.getByRole('button',{name:'Restore browser backup'}).click();
  await expect(editor).toHaveValue('Restored browser draft');
  await editor.fill(written);
  await toolbar.getByLabel('Code language').selectOption('java');
  await editor.evaluate(el=>{el.focus();el.setSelectionRange(el.value.length,el.value.length);});
  await toolbar.getByRole('button',{name:'Code',exact:true}).click();
  await expect(editor).toHaveValue(/```java/);
  await editor.evaluate(el=>{el.focus();el.setSelectionRange(el.value.length,el.value.length);});
  await toolbar.getByLabel('Screenshot file').setInputFiles(fileURLToPath(new URL('../../static/front/hero/mock3.jpg',import.meta.url)));
  await expect(editor).toHaveValue(/\/media\/blog_images\/inline\//);
  await toolbar.getByRole('button',{name:'Preview',exact:true}).click();
  await expect(toolbar.getByRole('region',{name:'Tutorial preview'})).toBeVisible();
  await toolbar.getByRole('region',{name:'Tutorial preview'}).scrollIntoViewIfNeeded();
  await expect(toolbar.locator('.tutorial-prose table')).toBeVisible();
  await expect(toolbar.locator('.tutorial-prose img')).toBeVisible();
  await expect(toolbar.locator('.tutorial-code-language').first()).toHaveText('Python');
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  const codeText=await toolbar.locator('pre code').first().textContent();
  await toolbar.getByRole('button',{name:'Copy code',exact:true}).first().click();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),codeText);
  assert.equal(await toolbar.locator('pre code').first().evaluate(el=>getComputedStyle(el).color),'rgb(230, 237, 243)');
  await page.screenshot({path:'/tmp/melka-publishing-editor.png',fullPage:true});
  const saveResponse=page.waitForResponse(r=>r.url().includes('/api/frontend/admin/Blog/')&&r.request().method()==='POST',{timeout:15000});
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  const response=await saveResponse;
  assert.equal(response.status(),201);
  const sent=response.request().postData();
  assert.match(sent,/Hold/);
  await page.waitForURL(/\/dashboard\/change\/Blog\/\d+\/\?saved=Hold/);
  await expect(page.getByRole('status').filter({hasText:'Draft saved.'})).toBeVisible();
  const draftLibrary=await page.request.get(origin+'/tutorials/');
  assert.doesNotMatch(await draftLibrary.text(),/Browser tutorial publishing check/);
  const publishResponse=page.waitForResponse(r=>r.url().includes('/api/frontend/admin/Blog/')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Publish tutorial',exact:true}).click();
  const published=await publishResponse;
  assert.equal(published.status(),200);
  assert.match(published.request().postData(),/Published/);
  await page.waitForURL(/\/dashboard\/change\/Blog\/\d+\/\?saved=Published/);
  await expect(page.getByRole('status').filter({hasText:'Tutorial published successfully.'})).toBeVisible();
  await expect(page.getByRole('link',{name:'Open on the public portal'})).toBeVisible();
  await page.goto(origin+'/tutorials/');
  await expect(page.getByRole('heading',{name:'Browser tutorial publishing check',exact:true})).toBeVisible();
  await page.getByRole('heading',{name:'Browser tutorial publishing check',exact:true}).getByRole('link').click();
  await expect(page.locator('.tutorial-prose')).toContainText('A tutorial body.');
  await expect(page.getByRole('button',{name:'Copy code'}).first()).toBeVisible();
  const publicPage=await browser.newPage();
  await publicPage.goto(page.url());
  await expect(publicPage.locator('.tutorial-prose')).toContainText('A tutorial body.');
  assert.deepEqual(errors,[]);
  console.log('PASS validation feedback, all formatting tools, screenshot upload, live preview, backup restore, draft privacy, Publish button, success confirmation and anonymous public article.');
} finally {await browser.close();}
